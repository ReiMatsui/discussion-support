"""名乗りの検出——「TBSの寺島です」「上潮と申します」をテキストから拾う（§49.11）.

**解く問題**: 会見・初対面の会議・オンライン会議では、話者が発言の頭で
名乗る。これは人間が話者を見分けるのに使っている独立の証拠で、声紋が
チャネル劣化（遠距離マイク・残響。§49.10）でぎりぎりの誤一致を出す場面
でも、テキストは崩れない。検出したら「名乗った名前の人物」として席を
立て、以後は本人の声紋を育てる。

**後ろ向きのフィルタではない**: 誤りをテキストで消すのではなく、積極的な
証拠を情報源として1つ足す。守備範囲は名乗りのある場面に限られるが、
副産物として議事録に最初から実名が付く。

校正（2026-08-01, 手持ち81ラン=千葉13+rehacq3+AMI3+講義+会見ほか）:
  - 会見の名乗り5件を5件とも検出（と申します1・組織+名前4）
  - 他の80ラン（雑談・討論・講義・英語）で誤発火0件
  - 素朴な「〜の◯◯です」だけだと雑談の「恋の話なんですけど」等で70件
    誤発火する。**組織語彙の要求が誤発火を全て消した**
  - 「◯◯さんです/様です」は他人の紹介なので除外する

語彙の原則（2026-08-01 ユーザーと合意）: **個人名は書かない**（名前は常に
ワイルドカードで捕る）。固有名の追加はカテゴリ接尾語（〜新聞・〜大学等）で
表せない組織名に限り、取りこぼしの実測が出てから足す。特定の検証素材に
合わせた調整はしない。
"""
from __future__ import annotations

import re

# 名乗りの直前に来る組織・所属の語彙。この要求が雑談での誤発火を消す（上記校正）。
_ORG = (
    r"(?:新聞|テレビ|放送|通信|通信社|株式会社|会社|大学|大学院|研究所|研究室"
    r"|学部|学科|省|庁|市役所|区役所|役場|銀行|証券|商事|工業|電機|製作所"
    r"|事務所|法律事務所|クリニック|病院|組合|協会|財団|機構"
    r"|NHK|TBS|MX|フジ|日経|共同|時事)"
)
# 前置型の会社表記（「株式会社◯◯の…」）。接尾語型（東京新聞の…）と違い、
# 語彙と「の」の間に社名が挟まる（コテンラジオ #4/#6「株式会社古典の
# 深井龍之介です」で取りこぼした実測 2026-08-02, §49.13）。緩めすぎない
# よう、この形だけは法人格の前置語に限る
_ORG_PREFIX = r"(?:株式会社|有限会社|合同会社|一般社団法人|NPO法人)"
# 他人の紹介（「続いては田中さんです」）は名乗りではない
_EXCLUDE = re.compile(r"(さん|様|氏|君|先生)(です|と申します)")
_TO_MOUSHIMASU = re.compile(r"([一-龥ぁ-んァ-ヶーA-Za-z]{2,8})と申します")
_ORG_NO_NAME = re.compile(
    r"(?:" + _ORG + r"|" + _ORG_PREFIX + r"[一-龥ぁ-んァ-ヶーA-Za-z]{1,10}?)"
    r"の\s*([一-龥ァ-ヶーA-Za-z]{2,6})です")
# 名乗りは発話の頭にある。後半まで見ると引用や伝聞を拾い始める
_HEAD_CHARS = 45


# --- LLM判定の二段構え（§49.14）------------------------------------------
# 1段目: 緩い候補フィルタ（高再現・低精度。83ラン27,672発話中0.5%に絞り、
# 既知の名乗りを全て通す実測）。2段目: 安いLLMに判定させる（eval/nanori_llm.py
# で 精度100%・再現18/18 を確認）。判定の指示と氏名の門はここが正本で、
# 評価スクリプトと本番ワーカーの両方がこれを使う（二重定義しない）。
LLM_CANDIDATE_RE = re.compile(
    r"(申します|といいます|と言います|でございます"
    r"|の\s*[一-龥ぁ-んァ-ヶーA-Za-z]{2,8}(です|でした))")
LLM_CANDIDATE_HEAD = 45     # 名乗りは頭にある（後半まで見ると引用を拾う）
LLM_JUDGE_HEAD = 160        # 判定に渡す文脈（120だと名前が切れた実測: 樋口）

NANORI_JUDGE_INSTRUCTIONS = """\
各発話について、話者が**自分自身を名乗っている**(自己紹介している)かを判定してください。
- 他人の紹介(「続いては田中さんです」)、引用、呼びかけ、単なる「〜です」文は名乗りではない
- 他人を紹介してから自分も名乗る発話(「…の田中さんと、私、鈴木で…」)は、**自分の名前だけ**を抜き出す
- 音声認識の聞き取りが崩れていて氏名として不自然な場合は nanori=false にする
- 「私は賛成です」のような代名詞+意見は名乗りではない。代名詞(私/自分/僕等)を name にしない
- 名乗りなら、名乗った氏名(姓または姓名。所属・肩書きは含めない)を抜き出す"""

NAME_MAX_CHARS = 8
# 代名詞は氏名ではない（言語的事実。評価2周目で「私は賛成です」の
# 名前=私 を実測したことによる門）
PRONOUNS = frozenset({"私", "わたし", "わたくし", "自分", "僕", "ぼく",
                      "俺", "おれ", "当方", "こちら", "うち"})


def is_llm_candidate(text: str) -> bool:
    """LLM判定に回す価値のある発話か（緩い事前フィルタ）."""
    return LLM_CANDIDATE_RE.search(str(text or "")[:LLM_CANDIDATE_HEAD]) is not None


def plausible_name(name) -> bool:
    """LLMが返した氏名が登録に値するか（空・長さ・代名詞の門。中身は問わない）."""
    n = str(name or "").strip()
    return bool(n) and len(n) <= NAME_MAX_CHARS and n not in PRONOUNS


def detect_nanori(text: str) -> str | None:
    """発話テキストから名乗りを検出し、名乗った名前を返す（無ければ None）.

    戻り値の名前は STT の聞き取りに依存する（会見の実測でも「産経」が
    「三軒」になった）。誤字は既存の UI リネーム（rekey）で直せるので、
    ここでは直さない。
    """
    head = str(text or "")[:_HEAD_CHARS]
    if _EXCLUDE.search(head):
        return None
    m = _TO_MOUSHIMASU.search(head)
    if m:
        # 「三軒新聞の上潮と申します」→ 最後の「の」より後ろが名前
        return m.group(1).split("の")[-1]
    m = _ORG_NO_NAME.search(head)
    if m:
        return m.group(1)
    return None
